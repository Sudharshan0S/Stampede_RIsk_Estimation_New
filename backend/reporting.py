"""Static chart (PNG), TXT and PDF report generation.

Every number comes from the result dictionary produced by predictor.py (which comes from the notebooks' pipeline) - nothing is invented here.
The two notebook figures (full timeline, 10 diagnostics) are produced by visualization.py; this module adds a few compact dark-theme charts.
"""
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
from fpdf import FPDF

from config import CHARTS_DIR, REPORTS_DIR

_STYLE = {"figure.facecolor": "#0a0d17", "axes.facecolor": "#0d1120", "axes.edgecolor": "#333c5c", "axes.labelcolor": "#c7cbe0", "xtick.color": "#8b93b0",
          "ytick.color": "#8b93b0", "text.color": "#e6e8f5", "grid.color": "#1a2036", "font.size": 10}
ACCENT, CYAN, WARN, CRIT = "#7c5cff", "#3ee6de", "#f2c94c", "#ff4d5e"


def _line_chart(path, x, series, title, ylabel, events=(), ylim=None, hlines=()):
    with plt.rc_context(_STYLE):
        fig, ax = plt.subplots(figsize=(7.5, 3.2), dpi=140)
        for label, y, color in series:
            ax.plot(x, y, color=color, linewidth=1.6, label=label)
        for e in events: ax.axvspan(e["start_s"], e["end_s"], color=CRIT, alpha=0.14, lw=0)
        for h in hlines: ax.axhline(h, color="#555e80", ls="--", lw=0.6)
        ax.set_title(title, fontsize=12, loc="left", fontweight="bold"); ax.set_xlabel("Time (s)"); ax.set_ylabel(ylabel); ax.grid(alpha=0.35, linewidth=0.5)
        if ylim: ax.set_ylim(*ylim)
        if len(series) > 1: ax.legend(fontsize=8, facecolor="#0d1120", edgecolor="#333c5c")
        fig.tight_layout(); fig.savefig(path, facecolor=fig.get_facecolor()); plt.close(fig)


def _bar_chart(path, labels, values, title, ylabel, color=ACCENT):
    with plt.rc_context(_STYLE):
        fig, ax = plt.subplots(figsize=(7, 3.2), dpi=140)
        ax.bar(labels, values, color=color); ax.set_title(title, fontsize=12, loc="left", fontweight="bold"); ax.set_ylabel(ylabel); ax.grid(alpha=0.3, axis="y", linewidth=0.5)
        fig.tight_layout(); fig.savefig(path, facecolor=fig.get_facecolor()); plt.close(fig)


def generate_video_charts(timeline, events, pred_id):
    """Compact charts of the per-window timeline (one point per temporal window)."""
    if not timeline: return {}
    x = [r["time_s"] for r in timeline]
    col = lambda k: [float(r.get(k)) if r.get(k) is not None else float("nan") for r in timeline]
    spec = {
        "risk_chart": ("Risk score over time", "score (0-100)", [("raw", col("risk_score_raw"), "#8b93b0"), ("smoothed", col("risk_score"), CRIT)], (0, 100), (20, 57.5, 67.5)),
        "crowd_chart": ("Crowd count over time", "people", [("count", col("count"), ACCENT)], None, ()),
        "speed_chart": ("Crowd speed over time", "px / step (work resolution)", [("mean", col("mean_speed"), CYAN), ("p95", col("p95_speed"), WARN)], None, ()),
        "abnormality_chart": ("Abnormality evidence (noisy-OR)", "score (0-1)", [("abnormality", col("abnormality_score"), ACCENT)], (0, 1), ()),
    }
    paths = {}
    for key, (title, ylabel, series, ylim, hl) in spec.items():
        p = CHARTS_DIR / f"{key}_{pred_id}.png"; _line_chart(p, x, series, title, ylabel, events, ylim, hl); paths[key] = str(p)
    return paths


def generate_image_charts(result, pred_id):
    """Single-image charts: head-point counts and the crowd-regime position."""
    paths = {}
    p = CHARTS_DIR / f"count_chart_{pred_id}.png"
    _bar_chart(p, ["Accepted heads", "Uncertain", "Density-map sum"], [result["crowd_count"], result["n_uncertain"], result.get("density_map_sum") or 0.0],
               "Crowd count estimate", "people", ACCENT); paths["count_chart"] = str(p)
    return paths


def _ascii(s):
    """fpdf2 core fonts are latin-1 only."""
    return str(s).replace("\u2022", "-").replace("\u2192", "->").replace("\u2013", "-").replace("\u2014", "-").encode("latin-1", "replace").decode("latin-1")


def build_report_lines(title, headline_rows, sections):
    lines = ["=" * 70, title, "=" * 70, ""]
    for label, value in headline_rows: lines.append(f"{label:<34}: {value}")
    for head, body in sections:
        lines += ["", "-" * 70, head, "-" * 70]
        lines += list(body) if isinstance(body, (list, tuple)) else [str(body)]
    lines += ["", "Generated by CrowdVision AI - risk labels are DERIVED (weak) + synthetic-injection labels, not official stampede labels."]
    return lines


def generate_pdf_report(title, headline_rows, sections, path):
    pdf = FPDF(format="A4"); pdf.set_auto_page_break(auto=True, margin=18); pdf.add_page()
    pdf.set_font("Helvetica", "B", 16); pdf.set_text_color(30, 30, 40); pdf.cell(0, 10, _ascii(title), new_x="LMARGIN", new_y="NEXT"); pdf.ln(2)
    pdf.set_draw_color(200, 200, 210); pdf.line(10, pdf.get_y(), 200, pdf.get_y()); pdf.ln(5)
    pdf.set_font("Helvetica", "B", 11); pdf.set_text_color(20, 20, 30); pdf.cell(0, 8, "Key Metrics", new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "", 10); pdf.set_text_color(50, 50, 60)
    for label, value in headline_rows:
        pdf.set_x(pdf.l_margin); pdf.cell(75, 7, _ascii(label)); pdf.cell(0, 7, _ascii(value), new_x="LMARGIN", new_y="NEXT")
    for head, body in sections:
        pdf.ln(4); pdf.set_x(pdf.l_margin); pdf.set_font("Helvetica", "B", 11); pdf.set_text_color(20, 20, 30); pdf.cell(0, 8, _ascii(head), new_x="LMARGIN", new_y="NEXT")
        pdf.set_font("Helvetica", "", 9); pdf.set_text_color(50, 50, 60)
        for line in (body if isinstance(body, (list, tuple)) else str(body).split("\n")):
            if str(line).strip(): pdf.set_x(pdf.l_margin); pdf.multi_cell(0, 5, _ascii(line))
    pdf.ln(6); pdf.set_x(pdf.l_margin); pdf.set_font("Helvetica", "I", 8); pdf.set_text_color(140, 140, 150)
    pdf.multi_cell(0, 5, "Generated by CrowdVision AI. Risk labels are derived (weak) + synthetic-injection labels, not official stampede labels.")
    pdf.output(str(path)); return str(path)
